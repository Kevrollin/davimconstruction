// Self-hosts the Latin subsets of Inter and Manrope (both SIL Open Font License 1.1)
// so the site makes no third-party font requests (faster on mobile networks, no
// render-blocking cross-origin CSS). Writes public/fonts/*.woff2 + src/styles/fonts.css.
//
// Usage: node scripts/fetch-fonts.mjs
import { mkdirSync, writeFileSync } from 'fs'

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Inter:wght@400..600&family=Manrope:wght@300..800&display=swap'
// A modern browser UA makes Google return variable WOFF2 files.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text()
// Google's CSS lists one @font-face per subset, each preceded by a /* subset */ comment.
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)].filter(([, subset]) => subset === 'latin')
if (blocks.length < 2) throw new Error('Could not find latin @font-face blocks in Google Fonts CSS')

mkdirSync('public/fonts', { recursive: true })
let out = '/* Generated by scripts/fetch-fonts.mjs — Inter & Manrope, SIL Open Font License 1.1 (latin subset) */\n'
for (const [, , block] of blocks) {
  const family = block.match(/font-family:\s*'([^']+)'/)[1]
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1]
  const file = `${family.toLowerCase()}-latin-variable.woff2`
  writeFileSync(`public/fonts/${file}`, Buffer.from(await (await fetch(url)).arrayBuffer()))
  out += block.replace(url, `/fonts/${file}`) + '\n'
  console.log('saved', file)
}
writeFileSync('src/styles/fonts.css', out)
console.log('wrote src/styles/fonts.css')
